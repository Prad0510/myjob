"""Clustering utilities for job matching.

Provides two clustering strategies – HDBSCAN and KMeans – that operate on
job embeddings generated by SentenceTransformer.

The public API:
    cluster_jobs(job_embeddings: np.ndarray) -> Tuple[np.ndarray, np.ndarray, list]
        Returns (labels, centroids, unique_labels) where `labels[i]` is the cluster id for the
        i‑th job, `centroids` is the array of cluster centroids, and `unique_labels`
        maps each centroid row to its cluster label.
    assign_candidate_to_cluster(candidate_emb: np.ndarray, centroids: np.ndarray, unique_labels: list) -> int
        Returns the cluster label closest to the candidate embedding, or -1.
"""

import os
import logging
from typing import Tuple, List
import numpy as np
from sklearn.metrics.pairwise import cosine_distances
from sklearn.cluster import KMeans
import hdbscan

logger = logging.getLogger("myjob.clustering")


def _load_settings() -> dict:
    method = os.getenv("CLUSTER_METHOD", "hdbscan").lower()
    num_clusters = int(os.getenv("NUM_CLUSTERS", "10"))
    min_cluster = int(os.getenv("MIN_CLUSTER_SIZE", "3"))
    return {"method": method, "num_clusters": num_clusters, "min_cluster": min_cluster}


def cluster_jobs(job_embeddings: np.ndarray) -> Tuple[np.ndarray, np.ndarray, List[int]]:
    """Cluster job embeddings and return labels, centroids, and cluster label IDs.

    Parameters
    ----------
    job_embeddings: np.ndarray
        Shape ``(n_jobs, embed_dim)``.

    Returns
    -------
    labels: np.ndarray
        Cluster label for each job (``-1`` for noise when using HDBSCAN).
    centroids: np.ndarray
        Representative vector for each non-noise cluster.
    unique_labels: List[int]
        Cluster label ID corresponding to each row in ``centroids``.
    """
    cfg = _load_settings()
    method = cfg["method"]
    n_jobs = job_embeddings.shape[0]
    logger.info("Clustering %d jobs using %s", n_jobs, method)

    if n_jobs < 3:
        # Too few jobs for clustering; treat all as a single cluster
        return np.zeros(n_jobs, dtype=int), job_embeddings.mean(axis=0, keepdims=True), [0]

    if method == "kmeans":
        n_clusters = min(cfg["num_clusters"], n_jobs)
        km = KMeans(n_clusters=n_clusters, random_state=42, n_init="auto")
        labels = km.fit_predict(job_embeddings)
        centroids = km.cluster_centers_
        unique_labels = list(range(n_clusters))
        return labels, centroids, unique_labels

    elif method == "hdbscan":
        # Ensure min_cluster_size is appropriate for dataset size
        min_cluster = max(2, min(cfg["min_cluster"], n_jobs // 3))
        clusterer = hdbscan.HDBSCAN(min_cluster_size=min_cluster, metric="euclidean")
        labels = clusterer.fit_predict(job_embeddings)

        unique_non_noise = [int(l) for l in np.unique(labels) if l != -1]
        centroids_list = []
        for l in unique_non_noise:
            centroids_list.append(job_embeddings[labels == l].mean(axis=0))

        if centroids_list:
            centroids = np.vstack(centroids_list)
        else:
            centroids = np.empty((0, job_embeddings.shape[1]))

        return labels, centroids, unique_non_noise
    else:
        raise ValueError(f"Unsupported CLUSTER_METHOD: {method}")


def assign_candidate_to_cluster(
    candidate_emb: np.ndarray,
    centroids: np.ndarray,
    unique_labels: List[int]
) -> int:
    """Find the cluster label whose centroid is closest (cosine distance) to candidate.

    Returns ``-1`` if no valid clusters exist.
    """
    if centroids.size == 0 or not unique_labels:
        logger.warning("No cluster centroids available.")
        return -1

    # Cosine distance = 1 - cosine similarity
    distances = cosine_distances(candidate_emb.reshape(1, -1), centroids).flatten()
    best_idx = int(distances.argmin())
    return unique_labels[best_idx]


